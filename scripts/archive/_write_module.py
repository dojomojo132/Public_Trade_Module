MODULE_PATH.parent.mkdir(parents=True, exist_ok=True)
MODULE_PATH.write_bytes(content_bytes)
print(f"Written {len(content_bytes)}B to {MODULE_PATH}")
print(f"BOM: {content_bytes[:3] == b'\\xef\\xbb\\xbf'}")
print(f"CRLF count: {content_bytes.count(b'\\r\\n')}")
