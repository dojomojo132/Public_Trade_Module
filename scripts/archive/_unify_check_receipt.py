"""
Объединение двух потоков оформления чека в один универсальный алгоритм.

Изменения:
1. ВыполнитьОформлениеСРазделением — переписать вызов на unified ОформитьЧекНаСервере
2. ОформитьЧекиСРазделениемПоФОПНаСервере — УДАЛИТЬ полностью
3. ОформитьЧекНаСервере — ПЕРЕПИСАТЬ как универсальную функцию
"""
import re
import sys
from pathlib import Path

filepath = Path(r"d:\Git\Public_Trade_Module\Конфигурация_PTM_Analytics\DataProcessors\Анл_РабочееМестоКассира\Forms\Форма\Ext\Form\Module.bsl")

# Чтение с сохранением BOM и line endings
raw = filepath.read_bytes()
if raw[:3] == b'\xef\xbb\xbf':
    bom = b'\xef\xbb\xbf'
    text = raw[3:].decode('utf-8')
else:
    bom = b''
    text = raw.decode('utf-8')

has_crlf = '\r\n' in text
text = text.replace('\r\n', '\n')
original = text  # для проверки

# ============================================================
# 1. Замена тела ВыполнитьОформлениеСРазделением
# ============================================================
pattern1 = (
    r'(&НаКлиенте\n'
    r'Процедура ВыполнитьОформлениеСРазделением\(ВидОплаты, КассаНаличных\)\n)'
    r'(.*?)'
    r'(\nКонецПроцедуры)'
)
replacement1_body = (
    "\t\n"
    "\t// Универсальный вызов: КассаОплаты не задана, определяется из ФОП по ВидОплаты\n"
    "\tЕсли ОформитьЧекНаСервере(Неопределено, ВидОплаты) Тогда\n"
    "\t\tПоказатьПредупреждение(, \"Чек успешно пробит!\");\n"
    "\t\tОбъект.ТЧ.Очистить();\n"
    "\t\tОчиститьПоляСдачи();\n"
    "\tКонецЕсли;\n"
    "\t\n"
    "\tАктивироватьПоиск();\n"
    "\t"
)

def replace1(m):
    return m.group(1) + replacement1_body + m.group(3)

text, count = re.subn(pattern1, replace1, text, count=1, flags=re.DOTALL)
assert count == 1, f"ОШИБКА: ВыполнитьОформлениеСРазделением не найдена! (count={count})"
print("[OK] 1. ВыполнитьОформлениеСРазделением — тело заменено")

# ============================================================
# 2. Удаление ОформитьЧекиСРазделениемПоФОПНаСервере целиком
# ============================================================
# Ищем от директивы &НаСервере перед Функция до КонецФункции
pattern2 = (
    r'\n&НаСервере\n'
    r'Функция ОформитьЧекиСРазделениемПоФОПНаСервере\([^)]*\)\n'
    r'.*?'
    r'\nКонецФункции\n'
)

text, count = re.subn(pattern2, '\n', text, count=1, flags=re.DOTALL)
assert count == 1, f"ОШИБКА: ОформитьЧекиСРазделениемПоФОПНаСервере не найдена! (count={count})"
print("[OK] 2. ОформитьЧекиСРазделениемПоФОПНаСервере — удалена")

# ============================================================
# 3. Замена ОформитьЧекНаСервере на универсальную версию
# ============================================================
pattern3 = (
    r'&НаСервере\n'
    r'Функция ОформитьЧекНаСервере\(Знач КассаОплаты\)\n'
    r'.*?'
    r'\nКонецФункции'
)

new_function = r'''&НаСервере
Функция ОформитьЧекНаСервере(Знач КассаОплаты = Неопределено, Знач ВидОплаты = "")
	
	ФискальныйРежимВкл = НастройкиПоУмолчанию.ПолучитьФискальныйРежим();
	
	// 1. Маппинг НалГруппа → ФОП (один запрос на всё)
	МаппингФОП = Новый Соответствие;
	ЗапросФОП = Новый Запрос(
		"ВЫБРАТЬ
		|	Распределение.НалоговаяГруппа КАК НалоговаяГруппа,
		|	Распределение.ФОП КАК ФОП
		|ИЗ
		|	РегистрСведений.РаспределениеНалоговыхГрупп КАК Распределение"
	);
	ВыборкаФОП = ЗапросФОП.Выполнить().Выбрать();
	Пока ВыборкаФОП.Следующий() Цикл
		МаппингФОП.Вставить(ВыборкаФОП.НалоговаяГруппа, ВыборкаФОП.ФОП);
	КонецЦикла;
	
	// 2. Группировка сумм товаров по ФОП (для определения касс)
	СуммыПоФОП = Новый Соответствие; // ФОП → Сумма
	СуммаДок = 0;
	
	Для Каждого СтрТЧ Из Объект.ТЧ Цикл
		НалГруппа = СтрТЧ.Номенклатура.НалоговаяГруппа;
		ФОПНоменклатуры = Неопределено;
		
		Если ЗначениеЗаполнено(НалГруппа) Тогда
			ФОПНоменклатуры = МаппингФОП.Получить(НалГруппа);
		КонецЕсли;
		
		Если ФОПНоменклатуры <> Неопределено И ЗначениеЗаполнено(ФОПНоменклатуры) Тогда
			ТекСумма = СуммыПоФОП.Получить(ФОПНоменклатуры);
			Если ТекСумма = Неопределено Тогда
				СуммыПоФОП.Вставить(ФОПНоменклатуры, СтрТЧ.Сумма);
			Иначе
				СуммыПоФОП.Вставить(ФОПНоменклатуры, ТекСумма + СтрТЧ.Сумма);
			КонецЕсли;
		КонецЕсли;
		
		СуммаДок = СуммаДок + СтрТЧ.Сумма;
	КонецЦикла;
	
	// 3. Определение касс для оплаты
	ОплатаПоКассам = Новый Соответствие; // Касса → Структура(Сумма, ВидОплаты)
	
	Если ЗначениеЗаполнено(КассаОплаты) Тогда
		
		// Режим ВЫКЛ: единая касса для всех товаров
		ВидКассы = КассаОплаты.ВидКассы;
		Если ВидКассы = Перечисления.ВидыКасс.БанковскийСчет Тогда
			ТипОплаты = Перечисления.ВидыОплаты.Безналичные;
		Иначе
			ТипОплаты = Перечисления.ВидыОплаты.Наличные;
		КонецЕсли;
		ОплатаПоКассам.Вставить(КассаОплаты, Новый Структура("Сумма, ВидОплаты", СуммаДок, ТипОплаты));
		
	Иначе
		
		// Режим ВКЛ: кассы определяются из ФОП по ВидОплаты
		КассаНаличных = Неопределено;
		Если ВидОплаты = "Наличные" Тогда
			КассаНаличных = НастройкиПоУмолчанию.ПолучитьКассуНаличных();
		КонецЕсли;
		
		// Распределение сумм по кассам через ФОП
		Для Каждого КлючИЗначение Из СуммыПоФОП Цикл
			ТекФОП = КлючИЗначение.Ключ;
			ТекСумма = КлючИЗначение.Значение;
			
			Если ВидОплаты = "Наличные" Тогда
				КассаДляОплаты = КассаНаличных;
				ТипОплаты = Перечисления.ВидыОплаты.Наличные;
			Иначе
				КассаДляОплаты = ТекФОП.КассаБезналичных;
				ТипОплаты = Перечисления.ВидыОплаты.Безналичные;
			КонецЕсли;
			
			Если Не ЗначениеЗаполнено(КассаДляОплаты) Тогда
				Если ВидОплаты = "Наличные" Тогда
					Сообщить("Не определена касса наличных! Проверьте настройки по умолчанию.");
				Иначе
					Сообщить("Не указана касса безналичных для ФОП """ + Строка(ТекФОП) + """! Заполните в справочнике ФОП.");
				КонецЕсли;
				Возврат Ложь;
			КонецЕсли;
			
			// Свёртка по уникальным кассам
			ДанныеКассы = ОплатаПоКассам.Получить(КассаДляОплаты);
			Если ДанныеКассы = Неопределено Тогда
				ОплатаПоКассам.Вставить(КассаДляОплаты, Новый Структура("Сумма, ВидОплаты", ТекСумма, ТипОплаты));
			Иначе
				ДанныеКассы.Сумма = ДанныеКассы.Сумма + ТекСумма;
			КонецЕсли;
		КонецЦикла;
		
		// Товары без ФОП → на кассу наличных или первую доступную
		СуммаСФОП = 0;
		Для Каждого КлючИЗначение Из СуммыПоФОП Цикл
			СуммаСФОП = СуммаСФОП + КлючИЗначение.Значение;
		КонецЦикла;
		СуммаБезФОП = СуммаДок - СуммаСФОП;
		
		Если СуммаБезФОП > 0 Тогда
			Если ВидОплаты = "Наличные" И ЗначениеЗаполнено(КассаНаличных) Тогда
				ДанныеКассы = ОплатаПоКассам.Получить(КассаНаличных);
				Если ДанныеКассы = Неопределено Тогда
					ОплатаПоКассам.Вставить(КассаНаличных, Новый Структура("Сумма, ВидОплаты", СуммаБезФОП, Перечисления.ВидыОплаты.Наличные));
				Иначе
					ДанныеКассы.Сумма = ДанныеКассы.Сумма + СуммаБезФОП;
				КонецЕсли;
			ИначеЕсли ОплатаПоКассам.Количество() > 0 Тогда
				Для Каждого КлючИЗначение Из ОплатаПоКассам Цикл
					КлючИЗначение.Значение.Сумма = КлючИЗначение.Значение.Сумма + СуммаБезФОП;
					Прервать;
				КонецЦикла;
			КонецЕсли;
		КонецЕсли;
		
	КонецЕсли;
	
	// Проверка: хотя бы одна касса определена
	Если ОплатаПоКассам.Количество() = 0 Тогда
		Сообщить("Не удалось определить кассу для оплаты! Проверьте настройки.");
		Возврат Ложь;
	КонецЕсли;
	
	// Касса шапки — первая касса из списка оплат
	КассаШапки = Неопределено;
	Для Каждого КлючИЗначение Из ОплатаПоКассам Цикл
		КассаШапки = КлючИЗначение.Ключ;
		Прервать;
	КонецЦикла;
	
	// 4. Создание 1 ЧекККМ
	НачатьТранзакцию();
	Попытка
		НовыйЧек = Документы.ЧекККМ.СоздатьДокумент();
		НовыйЧек.Дата = ТекущаяДатаСеанса();
		НовыйЧек.Склад = Склад;
		НовыйЧек.Касса = КассаШапки;
		НовыйЧек.КассоваяСмена = Объект.КассоваяСмена;
		
		Если ФискальныйРежимВкл Тогда
			НовыйЧек.Статус = Перечисления.СтатусыЧекаККМ.Пробит;
		Иначе
			НовыйЧек.Статус = Перечисления.СтатусыЧекаККМ.Нефискальный;
		КонецЕсли;
		
		// Товары — ВСЕ строки ТЧ
		Для Каждого СтрТЧ Из Объект.ТЧ Цикл
			НоваяСтр = НовыйЧек.Товары.Добавить();
			НоваяСтр.Номенклатура = СтрТЧ.Номенклатура;
			НоваяСтр.Количество = СтрТЧ.Количество;
			НоваяСтр.Цена = СтрТЧ.Цена;
			НоваяСтр.Сумма = СтрТЧ.Сумма;
			НоваяСтр.НалоговаяГруппа = СтрТЧ.Номенклатура.НалоговаяГруппа;
			НоваяСтр.АкцизнаяМарка = СтрТЧ.АкцизнаяМарка;
		КонецЦикла;
		
		НовыйЧек.СуммаДокумента = СуммаДок;
		
		// Оплата — строка для каждой уникальной кассы
		Для Каждого КлючИЗначение Из ОплатаПоКассам Цикл
			Оплата = НовыйЧек.Оплата.Добавить();
			Оплата.КассаОплаты = КлючИЗначение.Ключ;
			Оплата.Сумма = КлючИЗначение.Значение.Сумма;
			Оплата.ВидОплаты = КлючИЗначение.Значение.ВидОплаты;
		КонецЦикла;
		
		НовыйЧек.Записать(РежимЗаписиДокумента.Проведение);
		ЗафиксироватьТранзакцию();
		
	Исключение
		ОтменитьТранзакцию();
		Сообщить("Ошибка проведения чека: " + ОписаниеОшибки());
		Возврат Ложь;
	КонецПопытки;
	
	Возврат Истина;
	
КонецФункции'''

text, count = re.subn(pattern3, new_function, text, count=1, flags=re.DOTALL)
assert count == 1, f"ОШИБКА: ОформитьЧекНаСервере не найдена! (count={count})"
print("[OK] 3. ОформитьЧекНаСервере — заменена на универсальную версию")

# ============================================================
# Проверка результата
# ============================================================
assert 'ОформитьЧекиСРазделениемПоФОПНаСервере' not in text, \
    "ОШИБКА: ОформитьЧекиСРазделениемПоФОПНаСервере всё ещё присутствует!"

assert 'Функция ОформитьЧекНаСервере(Знач КассаОплаты = Неопределено, Знач ВидОплаты = "")' in text, \
    "ОШИБКА: новая сигнатура ОформитьЧекНаСервере не найдена!"

assert 'ОформитьЧекНаСервере(Неопределено, ВидОплаты)' in text, \
    "ОШИБКА: вызов из ВыполнитьОформлениеСРазделением не найден!"

# Запись результата
if has_crlf:
    text = text.replace('\n', '\r\n')

filepath.write_bytes(bom + text.encode('utf-8'))

print("\n=== Все изменения применены успешно ===")
print(f"Файл: {filepath}")
print(f"BOM: {'да' if bom else 'нет'}, CRLF: {'да' if has_crlf else 'нет'}")
