"""
E2E тест фискализации: создание ЧекККМ → проведение → фискализация → проверка ФискальногоЧека
Обходит ограничение HTTP-сервиса MCP (VResourceHttpServiceServer crash при cross-extension dispatch)
"""
import subprocess, sys, os, time, tempfile

IB_PATH = r"D:\Confiq\Public Trade Module"
V8_EXE = r"C:\Program Files\1cv8\8.3.27.1719\bin\1cv8.exe"

# BSL-код теста: создаём ЧекККМ, проводим (запускает фискализацию), проверяем ФискальныйЧек
TEST_BSL = r'''
Попытка
    // 1. Найти кассу и склад
    Касса = Справочники.Кассы.НайтиПоНаименованию("Наличная касса");
    Склад = Справочники.Склады.НайтиПоНаименованию("Основной склад");
    
    // 2. Найти открытую смену
    Запрос = Новый Запрос;
    Запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 КС.Ссылка ИЗ Документ.КассоваяСмена КАК КС ГДЕ КС.Касса = &Касса И КС.Статус = ЗНАЧЕНИЕ(Перечисление.СтатусыКассовойСмены.Открыта) УПОРЯДОЧИТЬ ПО КС.Дата УБЫВ";
    Запрос.УстановитьПараметр("Касса", Касса);
    Выб = Запрос.Выполнить().Выбрать();
    Если НЕ Выб.Следующий() Тогда
        Сообщить("E2E_RESULT: FAIL | Нет открытой кассовой смены");
        Возврат;
    КонецЕсли;
    КассоваяСмена = Выб.Ссылка;
    
    // 3. Найти товар с остатком
    ЗапросТовар = Новый Запрос;
    ЗапросТовар.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 ОТ.Номенклатура КАК Номенклатура ИЗ РегистрНакопления.ОстаткиТоваров.Остатки КАК ОТ ГДЕ ОТ.КоличествоОстаток >= 5 И ОТ.Склад = &Склад";
    ЗапросТовар.УстановитьПараметр("Склад", Склад);
    ВыбТ = ЗапросТовар.Выполнить().Выбрать();
    Если НЕ ВыбТ.Следующий() Тогда
        Сообщить("E2E_RESULT: FAIL | Нет товара с остатком");
        Возврат;
    КонецЕсли;
    Номенклатура = ВыбТ.Номенклатура;
    
    // 4. Создать ЧекККМ
    Чек = Документы.ЧекККМ.СоздатьДокумент();
    Чек.Дата = ТекущаяДатаСеанса();
    Чек.Касса = Касса;
    Чек.Склад = Склад;
    Чек.КассоваяСмена = КассоваяСмена;
    Чек.Статус = Перечисления.СтатусыЧекаККМ.Пробит;
    
    СтрТовара = Чек.Товары.Добавить();
    СтрТовара.Номенклатура = Номенклатура;
    СтрТовара.Количество = 1;
    СтрТовара.Цена = 250;
    СтрТовара.Сумма = 250;
    
    СтрОплаты = Чек.Оплата.Добавить();
    СтрОплаты.ВидОплаты = Перечисления.ВидыОплаты.Наличные;
    СтрОплаты.КассаОплаты = Касса;
    СтрОплаты.Сумма = 250;
    
    Чек.СуммаДокумента = 250;
    
    // 5. Провести чек (запустит фискализацию через BSP-паттерн)
    Чек.Записать(РежимЗаписиДокумента.Проведение);
    НомерЧека = Строка(Чек.Номер);
    
    // 6. Проверить результат: есть ли ФискальныйЧек для этого ЧекККМ?
    ЗапросФЧ = Новый Запрос;
    ЗапросФЧ.Текст = "ВЫБРАТЬ ФЧ.Номер, ФЧ.Статус, ФЧ.ФискальныйНомер, ФЧ.Сумма ИЗ Документ.ФискальныйЧек КАК ФЧ ГДЕ ФЧ.ДокументОснование = &ЧекСсылка";
    ЗапросФЧ.УстановитьПараметр("ЧекСсылка", Чек.Ссылка);
    ВыбФЧ = ЗапросФЧ.Выполнить().Выбрать();
    
    Если ВыбФЧ.Следующий() Тогда
        Сообщить("E2E_RESULT: OK | ЧекККМ=" + НомерЧека + " | ФискЧек=" + Строка(ВыбФЧ.Номер) + " | Статус=" + Строка(ВыбФЧ.Статус) + " | ФискНомер=" + Строка(ВыбФЧ.ФискальныйНомер) + " | Сумма=" + Строка(ВыбФЧ.Сумма));
    Иначе
        Сообщить("E2E_RESULT: PARTIAL | ЧекККМ=" + НомерЧека + " проведён, но ФискальныйЧек НЕ создан");
    КонецЕсли;
    
Исключение
    Сообщить("E2E_RESULT: ERROR | " + ОписаниеОшибки());
КонецПопытки;

ЗавершитьРаботуСистемы(Ложь);
'''

def main():
    # Записать BSL-код во временный файл
    bsl_path = os.path.join(tempfile.gettempdir(), "e2e_fiscal_test.bsl")
    with open(bsl_path, "w", encoding="utf-8-sig") as f:
        f.write(TEST_BSL)
    
    print(f"BSL-тест: {bsl_path}")
    print(f"ИБ: {IB_PATH}")
    print("Запуск 1cv8.exe /Execute...")
    print()
    
    cmd = [
        V8_EXE,
        "ENTERPRISE",
        f'/F"{IB_PATH}"',
        "/N", "Admin",
        f'/Execute"{bsl_path}"',
        "/DisableStartupDialogs",
        "/DisableStartupMessages",
    ]
    
    start = time.time()
    result = subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=120,
    )
    elapsed = time.time() - start
    
    print(f"Exit code: {result.returncode} ({elapsed:.1f} сек)")
    if result.stdout:
        print(f"STDOUT:\n{result.stdout}")
    if result.stderr:
        print(f"STDERR:\n{result.stderr}")
    
    # Также проверить вывод через сообщения (1С пишет Сообщить в stdout)
    output = result.stdout + result.stderr
    if "E2E_RESULT:" in output:
        for line in output.splitlines():
            if "E2E_RESULT:" in line:
                print(f"\n{'='*60}")
                print(f"  {line.strip()}")
                print(f"{'='*60}")
    else:
        print("\n⚠️ Результат E2E_RESULT не найден в выводе.")
        print("Проверьте ФискальныйЧек через MCP execute_query.")

if __name__ == "__main__":
    main()
