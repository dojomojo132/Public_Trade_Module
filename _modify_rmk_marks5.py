"""Добавить проверку акцизных марок в процедуру Рассчитать.
В фискальном режиме нельзя оформить продажу с незаполненными марками.
"""
import pathlib

paths = [
    pathlib.Path(r"D:\Git\Public_Trade_Module\Конфигурация\DataProcessors\РабочееМестоКассира\Forms\Форма\Ext\Form\Module.bsl"),
    pathlib.Path(r"D:\Git\Public_Trade_Module\Конфигурация\Проверка\DataProcessors\РабочееМестоКассира\Forms\Форма\Ext\Form\Module.bsl"),
]

old = """Процедура Рассчитать(Команда)
\t
\tЕсли Объект.ТЧ.Количество() = 0 Тогда
\t\tПоказатьПредупреждение(, "Чек пуст!");
\t\tВозврат;
\tКонецЕсли;
\t
\t// В зависимости от режима - продажа или возврат
\tЕсли РежимРаботы = "Возврат" Тогда"""

new = """Процедура Рассчитать(Команда)
\t
\tЕсли Объект.ТЧ.Количество() = 0 Тогда
\t\tПоказатьПредупреждение(, "Чек пуст!");
\t\tВозврат;
\tКонецЕсли;
\t
\t// В фискальном режиме: проверяем что все акцизные марки заполнены
\tЕсли РежимРаботы <> "Возврат" Тогда
\t\tФискальныйРежимВкл = ПолучитьФискальныйРежимНаСервере();
\t\tЕсли ФискальныйРежимВкл Тогда
\t\t\tДля Каждого СтрТЧ Из Объект.ТЧ Цикл
\t\t\t\tЕсли СтрТЧ.МаркаСтатус = 1 Тогда
\t\t\t\t\tПоказатьПредупреждение(, "Не все акцизные марки заполнены! Нажмите на красный индикатор (X) для ввода марки.");
\t\t\t\t\tВозврат;
\t\t\t\tКонецЕсли;
\t\t\tКонецЦикла;
\t\tКонецЕсли;
\tКонецЕсли;
\t
\t// В зависимости от режима - продажа или возврат
\tЕсли РежимРаботы = "Возврат" Тогда"""

for path in paths:
    folder = "Конфигурация" if "Проверка" not in str(path) else "Проверка"
    content = path.read_text(encoding='utf-8-sig')
    count = content.count(old)
    if count == 1:
        content = content.replace(old, new, 1)
        path.write_text(content, encoding='utf-8-sig')
        print(f"✓ {folder}: OK")
    else:
        print(f"✗ {folder}: {count} вхождений")

print("Готово!")
